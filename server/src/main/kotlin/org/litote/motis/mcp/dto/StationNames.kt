package org.litote.motis.mcp.dto

import io.github.oshai.kotlinlogging.KotlinLogging
import java.text.Normalizer
import kotlin.math.cos
import kotlin.math.floor
import kotlin.math.hypot
import kotlin.time.measureTimedValue

private val logger = KotlinLogging.logger {}

/** Languages of the names of the stations (columns of `stations/stations.tsv`, in this order). */
val STATION_LANGUAGES = listOf("fr", "es", "en", "nl", "de", "it")

/**
 * The first of [this] (ISO 639-1 codes, possibly with a region: "fr-FR") with names of stations, null when there is none
 * (the names are then displayed as the feeds write them).
 */
fun List<String>?.stationLanguage(): String? =
    this?.firstNotNullOfOrNull { tag -> tag.trim().lowercase().substringBefore('-').substringBefore('_').takeIf { it in STATION_LANGUAGES } }

/** Lowercase, without accent nor punctuation, words separated by one space: "Nîmes – Centre" -> "nimes centre". */
internal fun normalizeName(text: String): String {
    val plain = Normalizer.normalize(text.lowercase(), Normalizer.Form.NFD).filter { Character.getType(it) != Character.NON_SPACING_MARK.toInt() }
    return plain.map { if (it.isLetterOrDigit()) it else ' ' }.joinToString("").trim().replace(Regex("\\s+"), " ")
}

/**
 * Railway stations with their name in each language of [STATION_LANGUAGES], to display the same station under the same
 * name whatever the feed ("NIMES" of the Spain-France high-speed feed, "Nîmes Centre" of the SNCF) and in the language of
 * the user ("Girona" -> "Gérone", "Barcelona Sants" -> "Barcelone Sants"). Generated by `scripts/generate_station_names.py`.
 *
 * Only the city part of a name is translated: the rest ("Sants", "Part-Dieu") is kept as the feed writes it.
 */
class StationNames(tsv: String) {
    /** Number of stations. */
    val size: Int get() = stations.size


    private class Station(
        val name: String,
        val city: String,
        val lat: Double,
        val lon: Double,
        val main: Boolean,
        /** Name in each of [STATION_LANGUAGES]. */
        val names: List<String>,
    ) {
        val normalizedCity = normalizeName(city)

        /** The city of the station in [language], null when the name has no city part or no translation. */
        fun city(language: Int): String? {
            val rest = name.substring(city.length)
            return names[language].takeIf { city.isNotEmpty() && it.endsWith(rest) }?.removeSuffix(rest)?.takeIf { it.isNotEmpty() }
        }
    }

    private val stations: List<Station> =
        tsv.lineSequence()
            .filter { it.isNotBlank() && !it.startsWith("#") }
            .mapNotNull { line ->
                val cells = line.split('\t')
                // uic, lat, lon, main, name, city, then a name per language
                if (cells.size < 6 + STATION_LANGUAGES.size) return@mapNotNull null
                val name = cells[4]
                Station(
                    name = name,
                    city = cells[5],
                    lat = cells[1].toDoubleOrNull() ?: return@mapNotNull null,
                    lon = cells[2].toDoubleOrNull() ?: return@mapNotNull null,
                    main = cells[3] == "1",
                    names = STATION_LANGUAGES.indices.map { cells[6 + it].ifBlank { name } },
                )
            }
            .toList()

    private val grid: Map<Pair<Int, Int>, List<Station>> = stations.groupBy { cell(it.lat, it.lon) }
    private val byCity: Map<String, List<Station>> = stations.filter { it.city.isNotEmpty() }.groupBy { it.normalizedCity }
    private val byName: Map<String, List<Station>> = stations.groupBy { normalizeName(it.name) }
    private val maxCityWords = byCity.keys.maxOfOrNull { it.count { c -> c == ' ' } + 1 } ?: 0

    /**
     * [name] of a stop in [language] (one of [STATION_LANGUAGES]): when it begins with the name of a city, this one is
     * written in [language] ("Gérone", "Barcelone Sants"), and a stop named after the city only (the high-speed feed:
     * "Nimes") takes the name of its station ("Nîmes Centre"). With the coordinates, the stop must be at a station of
     * this city (not a bus stop of the same name elsewhere). The name is returned as is for the other stops.
     */
    fun localize(name: String, lat: Double?, lon: Double?, language: String): String {
        val index = STATION_LANGUAGES.indexOf(language)
        if (index < 0) return name
        val candidates = if (lat != null && lon != null) nearby(lat, lon) else null
        val words = name.trim().split(Regex("\\s+"))
        for (count in minOf(maxCityWords, words.size) downTo 1) {
            val prefix = words.take(count).joinToString(" ")
            val key = normalizeName(prefix)
            val sameCity = (byCity[key] ?: continue).let { all -> if (candidates == null) all else all.filter { it in candidates } }
            if (sameCity.isEmpty()) continue
            val rest = name.trim().substring(prefix.length)
            // named after the city only: the name of the (main) station
            val station = sameCity.singleOrNull() ?: sameCity.singleOrNull { it.main }
            if (rest.isBlank()) return station?.names?.get(index) ?: sameCity.firstNotNullOfOrNull { it.city(index) } ?: name
            val city = sameCity.firstNotNullOfOrNull { it.city(index) } ?: return name
            return city + rest
        }
        // a station without city part ("Genève")
        val station = (byName[normalizeName(name)] ?: return name).let { all -> if (candidates == null) all else all.filter { it in candidates } }
        val translated = (station.singleOrNull() ?: station.singleOrNull { it.main })?.names?.get(index) ?: return name
        // the feed's spelling is kept ("Lyon-Part-Dieu") unless the station really has another name in the language
        return if (normalizeName(translated) == normalizeName(name)) name else translated
    }

    private fun nearby(lat: Double, lon: Double): Set<Station> {
        val (row, column) = cell(lat, lon)
        val metersPerDegreeLon = METERS_PER_DEGREE * cos(Math.toRadians(lat))
        return (row - 1..row + 1).flatMap { r -> (column - 1..column + 1).flatMap { c -> grid[r to c].orEmpty() } }
            .filter { hypot((it.lat - lat) * METERS_PER_DEGREE, (it.lon - lon) * metersPerDegreeLon) <= RADIUS_M }
            .toSet()
    }

    private fun cell(lat: Double, lon: Double): Pair<Int, Int> = floor(lat * 100).toInt() to floor(lon * 100).toInt()

    companion object {
        private const val METERS_PER_DEGREE = 111_320.0

        /** Distance (m) between a stop and its station: the stops of the same station are not all at the same place. */
        private const val RADIUS_M = 300.0

        /** The stations of the application, empty when the resource is missing. */
        val default: StationNames by lazy {
            val (names, elapsed) =
                measureTimedValue {
                    StationNames::class.java.getResourceAsStream("/stations/stations.tsv")?.use { String(it.readBytes(), Charsets.UTF_8) }.orEmpty().let(::StationNames)
                }
            // read once per process (a Lambda environment): its cost is part of the first request asking for a language
            logger.debug { "Stations loaded: ${names.size} in ${elapsed.inWholeMilliseconds} ms" }
            names
        }
    }
}
